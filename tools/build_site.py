#!/usr/bin/env python3
"""Assemble the static site: one folder per story, plus a landing page.

For every stories/<name>/ that holds events.json and story.json, this writes
_site/<name>/ with the player (player/*), the story's JSON files, any files under
the story's assets/ folder, and a data.js that wraps the JSON so the page also
works when opened from disk. It then writes _site/index.html, which links to
every story.

A story may declare "schema" in story.json; the build refuses a story whose
schema is newer than the player's STORY_SCHEMA.

Usage:
    python3 tools/build_site.py    # build every story into _site/; each
                                   # _site/<story>/ also opens straight from disk
"""

import argparse
import datetime
import html
import json
import re
import shutil
import sys
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parent.parent
PLAYER = ROOT / "player"
STORIES = ROOT / "stories"
SITE = ROOT / "_site"
PLAYER_FILES = ("index.html", "style.css", "app.js")
# Story folders are named like blog posts, YYYY-MM-DD-<slug>, so they sort by date.
FOLDER_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})-[a-z0-9]+(?:-[a-z0-9]+)*$")


def as_js(value: object) -> str:
    # String contents can contain "</"; "<\/" is the same string to a JS parser
    # and cannot close the surrounding <script> element.
    return json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace(
        "</", "<\\/"
    )


def player_constant(name: str) -> str:
    src = (PLAYER / "app.js").read_text(encoding="utf-8")
    match = re.search(rf"var {name} = '?([^';]+)'?;", src)
    if not match:
        sys.exit(f"player/app.js does not define {name}")
    return match.group(1)


def data_js(events: list, story: dict) -> str:
    return (
        "// Generated by tools/build_site.py from events.json and story.json. Do not edit.\n"
        f"window.REPLAY_EVENTS = {as_js(events)};\n"
        f"window.REPLAY_STORY = {as_js(story)};\n"
    )


def load_story(folder: Path, max_schema: int) -> tuple[list, dict]:
    events = json.loads((folder / "events.json").read_text(encoding="utf-8"))
    story = json.loads((folder / "story.json").read_text(encoding="utf-8"))
    schema = story.get("schema", 1)
    if schema > max_schema:
        sys.exit(
            f"{folder.name}: story schema {schema} is newer than the player's {max_schema}"
        )
    n = len(events)
    for ref in story.get("chapters", []) + story.get("cards", []):
        if not 0 <= ref["at"] < n:
            sys.exit(f"{folder.name}: anchor {ref['at']} outside 0..{n - 1}: {ref}")
    # The folder date must be the session's date in the story's own timezone,
    # the same date the player shows.
    match = FOLDER_RE.match(folder.name)
    if not match:
        sys.exit(f"{folder.name}: story folders must be named YYYY-MM-DD-<slug>")
    tz = ZoneInfo(story["timezone"]) if story.get("timezone") else datetime.UTC
    session_date = (
        datetime.datetime.fromtimestamp(events[0]["t"], tz).date().isoformat()
    )
    if match.group(1) != session_date:
        sys.exit(
            f"{folder.name}: folder date {match.group(1)} != session date {session_date}"
        )
    return events, story


def landing_page(entries: list[dict], version: str) -> str:
    items = "\n".join(
        f"""      <li>
        <a href="{html.escape(e["slug"])}/">
          <time class="d" datetime="{e["date"]}">{e["date"]}</time>
          <span class="t">{html.escape(e["title"])}</span>
          <span class="s">{html.escape(e["subtitle"])}</span>
          <span class="m">{e["events"]} events</span>
        </a>
      </li>"""
        for e in entries
    )
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Claude session replays</title>
<style>
  :root {{ color-scheme: dark; --bg: #0b0d10; --fg: #ecebe6; --fg2: #a9adb3; --acc: #5be0b3; --border: #232a33; }}
  * {{ box-sizing: border-box; }}
  body {{ margin: 0; background: var(--bg); color: var(--fg); font: 16px/1.6 system-ui, -apple-system, "Segoe UI", sans-serif; }}
  main {{ max-width: 860px; margin: 0 auto; padding: 4rem 16px; }}
  h1 {{ font-family: ui-monospace, "JetBrains Mono", Menlo, monospace; font-size: clamp(2rem, 6vw, 3.2rem); line-height: 1.1; margin: 0 0 1rem; }}
  p.lead {{ color: var(--fg2); margin: 0 0 2.5rem; }}
  ul {{ list-style: none; margin: 0; padding: 0; display: grid; gap: 1rem; }}
  .d {{ position: absolute; top: 1rem; right: 1.1rem; font-family: ui-monospace, Menlo, monospace; font-size: 0.75rem; color: var(--acc); border: 1px solid rgba(91, 224, 179, 0.35); background: rgba(91, 224, 179, 0.06); border-radius: 999px; padding: 0.15rem 0.6rem; }}
  a {{ position: relative; display: grid; gap: 0.3rem; padding: 1.2rem 1.3rem; border: 1px solid var(--border); border-radius: 12px; color: inherit; text-decoration: none; transition: border-color 0.2s; }}
  a:hover, a:focus-visible {{ border-color: var(--acc); outline: none; }}
  .t {{ font-weight: 600; font-size: 1.15rem; padding-right: 7.5rem; }}
  .s {{ color: var(--fg2); }}
  .m {{ color: var(--acc); font-family: ui-monospace, Menlo, monospace; font-size: 0.8rem; }}
  footer {{ margin-top: 3rem; color: var(--fg2); font-size: 0.8rem; font-family: ui-monospace, Menlo, monospace; }}
</style>
</head>
<body>
<main>
  <h1>Claude session replays</h1>
  <p class="lead">Real Claude Code sessions, replayed with commentary. Scroll through each one, or press play, and open any tool call to see exactly what went in and what came back.</p>
  <ul>
{items}
  </ul>
  <footer>player {html.escape(version)}</footer>
</main>
</body>
</html>
"""


def main() -> None:
    argparse.ArgumentParser(description=__doc__.splitlines()[0]).parse_args()

    version = player_constant("PLAYER_VERSION")
    max_schema = int(player_constant("STORY_SCHEMA"))
    if SITE.exists():
        shutil.rmtree(SITE)
    SITE.mkdir()

    entries = []
    # Newest first: the YYYY-MM-DD prefix makes reverse name order date order.
    for folder in sorted((p for p in STORIES.iterdir() if p.is_dir()), reverse=True):
        if (
            not (folder / "events.json").is_file()
            or not (folder / "story.json").is_file()
        ):
            print(f"skip {folder.name}: no events.json/story.json")
            continue
        events, story = load_story(folder, max_schema)
        out = SITE / folder.name
        out.mkdir()
        for name in PLAYER_FILES:
            shutil.copy2(PLAYER / name, out / name)
        for name in ("events.json", "story.json"):
            shutil.copy2(folder / name, out / name)
        if (folder / "assets").is_dir():
            shutil.copytree(folder / "assets", out / "assets")
        (out / "data.js").write_text(data_js(events, story), encoding="utf-8")
        entries.append(
            {
                "slug": folder.name,
                "date": folder.name[:10],
                "title": story.get("title", folder.name),
                "subtitle": story.get("subtitle", ""),
                "events": len(events),
            }
        )
        print(f"built {folder.name}: {len(events)} events")

    # Served at the URLs in their $id, for editors and external validators.
    shutil.copytree(ROOT / "schemas", SITE / "schemas")
    (SITE / "index.html").write_text(landing_page(entries, version), encoding="utf-8")
    (SITE / ".nojekyll").write_text("", encoding="utf-8")
    print(
        f"wrote {SITE.relative_to(ROOT)}/ with {len(entries)} stories (player {version})"
    )


if __name__ == "__main__":
    main()
