"""Assemble the static site: one folder per story, plus a landing page.

For every stories/<name>/ that holds events.json and story.json, this writes
_site/<name>/ with the player (player/*), the story's JSON files, any files under
the story's assets/ folder, and a data.js that wraps the JSON so the page also
works when opened from disk. It then writes _site/index.html, which links to
every story.

A story may declare "schema" in story.json; the build refuses a story whose
schema is newer than the player's STORY_SCHEMA.

Usage:
    python3 tools/build_site.py    # build every story into _site/; each
                                   # _site/<story>/ also opens straight from disk
"""

